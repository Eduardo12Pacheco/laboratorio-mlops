#!/usr/bin/env python3
"""Render the committed drill results table from the `drill-report/v1` JSON files (S24).

The table is generated, never hand-edited: every number in the documentation can be
traced back to a committed report and to the command that produced it. `--check` compares
the file on disk with a fresh render, so a stale table fails the documentation gate.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = "drill-report/v1"
SCENARIO_ORDER = ("drift", "gate-reject", "bad-batch", "rollback")
DEFAULT_RESULTS_DIR = ROOT / "docs" / "results"
DEFAULT_TABLE = DEFAULT_RESULTS_DIR / "results-table.md"

_HEADER = (
    "| Scenario | Weeks | Versions | Promotions | Rejections | Rollbacks | "
    "Quarantined | As-served RMSE | As-served MAE | As-served WAPE | "
    "Frozen-v1 RMSE | Frozen-v1 WAPE | RMSE ratio |"
)
_SEPARATOR = "|" + "|".join(["---"] + ["---:"] * 12) + "|"
_NOTE = (
    "_Generated by `uv run python scripts/render_results_table.py` from "
    "`docs/results/drill-*.json` (seed 42, schema `drill-report/v1`); do not edit by hand._"
)


def load_report(path: Path) -> dict[str, Any]:
    """Load and validate one committed drill report."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"{path}: report must be a JSON object")
    if payload.get("schema") != SCHEMA:
        raise ValueError(f"{path}: expected schema {SCHEMA!r}, got {payload.get('schema')!r}")
    summary = payload.get("summary")
    if not isinstance(summary, dict):
        raise ValueError(f"{path}: missing summary object")
    for key in ("as_served", "counterfactual_frozen_v1"):
        if not isinstance(summary.get(key), dict):
            raise ValueError(f"{path}: missing summary.{key}")
    return payload


def _metric(summary: dict[str, Any], section: str, key: str) -> float:
    value = summary[section][key]
    if not isinstance(value, int | float):
        raise ValueError(f"summary.{section}.{key} must be numeric")
    return float(value)


def _row(scenario: str, report: dict[str, Any]) -> str:
    summary = report["summary"]
    served_rmse = _metric(summary, "as_served", "rmse")
    frozen_rmse = _metric(summary, "counterfactual_frozen_v1", "rmse")
    ratio = served_rmse / frozen_rmse if frozen_rmse else 0.0
    cells = (
        scenario,
        str(report["weeks"]),
        str(summary["versions"]),
        str(summary["promotions"]),
        str(summary["rejections"]),
        str(summary["rollbacks"]),
        str(summary["quarantined_batches"]),
        f"{served_rmse:.4f}",
        f"{_metric(summary, 'as_served', 'mae'):.4f}",
        f"{_metric(summary, 'as_served', 'wape'):.4f}",
        f"{frozen_rmse:.4f}",
        f"{_metric(summary, 'counterfactual_frozen_v1', 'wape'):.4f}",
        f"{ratio:.4f}",
    )
    return "| " + " | ".join(cells) + " |"


def render_table(results_dir: Path = DEFAULT_RESULTS_DIR) -> str:
    """Render the Markdown table from the four committed scenario reports."""
    reports: dict[str, dict[str, Any]] = {}
    for name in SCENARIO_ORDER:
        path = results_dir / f"drill-{name}.json"
        if not path.exists():
            raise FileNotFoundError(f"missing drill report: {path}")
        reports[name] = load_report(path)
    lines = [_HEADER, _SEPARATOR]
    lines.extend(_row(name, reports[name]) for name in SCENARIO_ORDER)
    lines.extend(("", _NOTE))
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=DEFAULT_RESULTS_DIR,
        help="Directory holding `drill-*.json` (default: docs/results).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 when `results-table.md` differs from a fresh render.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    results_dir: Path = args.results_dir
    try:
        rendered = render_table(results_dir)
    except (FileNotFoundError, ValueError, json.JSONDecodeError) as error:
        print(f"results table error: {error}")
        return 1
    destination = results_dir / "results-table.md"
    if args.check:
        if not destination.exists():
            print(f"results table error: missing {destination}")
            return 1
        if destination.read_text(encoding="utf-8") != rendered:
            print(f"results table error: {destination} is stale; run without --check")
            return 1
        print("results table OK")
        return 0
    destination.write_text(rendered, encoding="utf-8")
    print(f"wrote {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
